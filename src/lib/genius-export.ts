/**
 * Genius XLS Export — writes TDS return data into Genius-compatible Excel templates.
 *
 * Output is BIFF8 (.xls) because Genius VBA uses Workbooks.Open which cannot
 * read OOXML (.xlsx) — giving Genius a .xlsx produces "Unable to get the Open
 * property of the Workbooks class" etc.
 *
 * Architecture — OLE2-container SPLICE, not a full regeneration:
 *
 * An earlier version of this file round-tripped the ENTIRE workbook through
 * SheetJS's own BIFF8 writer (read → edit cells → write, using its bookVBA
 * option to re-embed the VBA project). That correctly preserved the VBA
 * project bytes, but a direct OLE2-container comparison against the real
 * Genius template revealed SheetJS's writer regenerates the WHOLE compound
 * file from scratch and silently drops things it has no model for:
 *   - the "Ctls" stream (serialized state of any worksheet-embedded ActiveX
 *     controls)
 *   - the "CompObj" stream(s) (OLE type-identification metadata — used by
 *     OLE-aware hosts, like Genius itself, to confirm "this really is an
 *     Excel.Sheet.8", to validate the file before trusting it)
 *   - the standard "Root Entry" root-storage name (SheetJS's writer names it
 *     "R" instead — a deviation from what every genuine Excel-saved file uses)
 *   - the workbook's defined names (Print_Area, the dropdown-list source
 *     ranges on the hidden Master sheet) — SheetJS's BIFF8 writer has no
 *     support for re-emitting NAME records at all, confirmed via a completely
 *     unmodified read→write round trip losing them too
 *
 * Any of these could plausibly be why Genius's own VBA import macro — or
 * Excel's file-validation heuristics, especially for internet-downloaded
 * files — rejects a SheetJS-regenerated file even though the file "looks"
 * fine to SheetJS's own (lenient) reader.
 *
 * So instead of regenerating the whole file, we NEVER touch the original
 * template's OLE2 container at all except for one thing: we splice in a
 * freshly-written "Workbook" stream (the BIFF8 sub-stream that actually
 * holds cell data, sheet names, etc.) generated by SheetJS, and leave every
 * other stream — Ctls, CompObj, the full VBA project storage, Summary/
 * DocumentSummaryInformation, the root entry's name — byte-for-byte
 * untouched, copied directly from the source template:
 *
 *  1. Load .xls template (Supabase Storage → public folder fallback → error if missing)
 *  2. Parse the template with `cfb` (SheetJS's own compound-file library) —
 *     this is our BASE container; nothing on it changes except one stream.
 *  3. SEPARATELY, read the same template bytes with SheetJS's `xlsx` reader
 *     purely to get an editable cell/sheet-name model, write the required
 *     data into it, and serialize THAT to a standalone "donor" .xls buffer.
 *  4. Parse the donor buffer with `cfb`, extract just its "Workbook" stream.
 *  5. Splice that stream's bytes into the BASE container's "Workbook" entry.
 *  6. Serialize the (mostly-untouched) BASE container back to bytes — VBA
 *     project, Ctls, CompObj, root naming, and all other streams are
 *     whatever they were in the original file, never round-tripped through
 *     any writer at all.
 *
 * Verified against the real Genius template (SAG Infotech, "Export
 * Utility.xls", 44 OLE2 streams): after the splice, all 44 streams are
 * present with zero missing/extra, Ctls and every CompObj stream are
 * byte-identical to the source, the root entry is "Root Entry/" (not "R"),
 * and the VBA project — never touched by SheetJS at all in this approach —
 * is trivially byte-identical since it's the same untouched stream.
 *
 * The one remaining known gap: the donor "Workbook" stream (the part
 * SheetJS DOES generate) still can't carry the workbook's defined names,
 * because that's a limitation of SheetJS's BIFF8 writer regardless of how
 * the surrounding container is assembled. Those names back Excel's own
 * dropdown-list UI convenience on the blank template for a human filling it
 * in by hand — the decompiled Genius macro (see below) never references any
 * of them by name, only ever reading/writing sheet cells directly, so this
 * is confirmed low-risk rather than merely assumed to be.
 *
 * Sheet names are intentionally left EXACTLY as the template has them —
 * DeductorDetails, ChallanDetails, Annex-I_DeducteeDetails, etc., no spaces.
 * An earlier version of this file renamed them to space-separated display
 * names ("Deductor Details" etc.), on the assumption Genius's import
 * required that (a prior developer's note claimed "Genius importer looks
 * for exact names with spaces"). That assumption was never actually
 * verified and turned out to be backwards. With "Trust access to the VBA
 * project object model" enabled and Excel's VBProject object model, Module1
 * was extracted and decompiled directly (it's MS-OVBA-compressed; decoded
 * with a from-spec implementation of the documented decompression
 * algorithm, verified correct by producing clean, coherent VBA source).
 * Its VerifyData/VerifyDeductor/VerifyChallan/VerifyDeductee routines — the
 * actual logic wired to the sheet's own "Validate Data" ActiveX button —
 * reference sheets exclusively via Sheets("DeductorDetails"),
 * Sheets("ChallanDetails"), Sheets("Annex-I_DeducteeDetails"): zero
 * occurrences of any spaced variant anywhere in the source. Renaming the
 * sheets was silently breaking Genius's own lookups against its own
 * template — this file no longer renames anything.
 */

