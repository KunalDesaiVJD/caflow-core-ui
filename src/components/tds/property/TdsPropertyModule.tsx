/**
 * TDS on Property — the dedicated section in TDS Management.
 *
 * Kept entirely separate from the quarterly workspace (24Q/26Q/27Q/27EQ)
 * because a Form 141 Schedule B statement shares almost nothing with a
 * quarterly return: it is filed under the buyer's PAN rather than a TAN, its
 * period is a month rather than a quarter, and its challan IS the statement.
 * Showing property deals in the same list as quarterly filings would mean
 * every column header needed two meanings.
 *
 * This screen owns the transaction list and the read/write path; the editor
 * (TdsPropertyEditor) owns entry and the live computation. All arithmetic
 * lives in src/lib/tds/form141*.ts and is never duplicated here.
 *
 * Database access goes through the single `propertyTable` helper below rather
 * than casting at each call site — see its own note for why.
 */
