import { supabase } from "@/integrations/supabase/client";
import { useAuth } from "@/hooks/useAuth";
import { toast } from "sonner";
import { Card, CardContent } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Label } from "@/components/ui/label";
import { SearchableSelect } from "@/components/ui/searchable-select";
import { Skeleton } from "@/components/ui/skeleton";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Plus, Home, ArrowLeft, CalendarClock } from "lucide-react";
import { cn } from "@/lib/utils";

import { computeForm141ScheduleB } from "@/lib/tds/form141ScheduleB";
import { taxYearForDate, todayInIndia, FORM_141_FIRST_TAX_YEAR } from "@/lib/tds/form141";
import { TdsPropertyEditor } from "./TdsPropertyEditor";
import type { StoredDocument } from "./TdsPropertyUpload";
import type { AppliedExtraction, ResolvedQuery, FieldProvenance } from "./agreementExtraction";
import { challanFilingUpdate, type ChallanFields } from "@/lib/tds/form141Challan";
import {
  toForm141Deal,
  formatInr,
  emptyTransaction,
  resolveFilingBuyerPan,
  num,
  STATUS_BADGE,
  STATUS_LABEL,
  type PropertyDealBundle,
  type PropertyTransactionRow,
  type PropertyTxnStatus,
  type PropertyPartyRow,
  type PropertyInstalmentRow,
} from "./propertyDeal";

/**
 * The Supabase escape hatch, confined to ONE place.
 *
 * src/integrations/supabase/types.ts is regenerated by the CLI only
 * (CLAUDE.md §6) and does not know the tds_property_* tables until someone
 * runs the generator after applying migration 20260907090000. Without this,
 * every query and every payload in this file would carry its own cast —
 * twenty escape hatches instead of one, and twenty places to clean up later.
 *
 * Keeping it here means regenerating the types is a single deletion: drop
 * this helper, and every call site type-checks against the real schema.
 */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type UntypedQuery = any;
const propertyTable = (name: string): UntypedQuery => (supabase as UntypedQuery).from(name);

/** Postgres error shape we actually branch on, without pulling in a type the
 *  generated client does not export. */
const errorMessage = (e: unknown): string =>
  (typeof e === "object" && e !== null && "message" in e && typeof (e as { message: unknown }).message === "string")
    ? (e as { message: string }).message
    : "";

interface ClientOption {
  id: string;
  name: string | null;
  pan: string | null;
}

interface Props {
  clients: ClientOption[];
  isSuperadmin: boolean;
  resolveFirmId: () => Promise<string | null>;
}

/** Tax Years to offer. Form 141 begins at 2026-27; there is no earlier year to
 *  show, because before that the form did not exist. */
function taxYearOptions(): string[] {
  const current = taxYearForDate(todayInIndia());
  const start = parseInt(FORM_141_FIRST_TAX_YEAR.slice(0, 4), 10);
  const now = Math.max(start, parseInt(current.slice(0, 4), 10));
  const years: string[] = [];
  for (let y = start; y <= now + 1; y++) years.push(`${y}-${String(y + 1).slice(2)}`);
  return years;
}

/** New child rows carry a client-generated id so React can key them before
 *  they exist in the database. The prefix is what tells the save path which
 *  rows to INSERT rather than UPDATE. */
const isNew = (id: string) => !id || id.startsWith("new-");

export function TdsPropertyModule({ clients, isSuperadmin, resolveFirmId }: Props) {
  const { user } = useAuth();
  const years = useMemo(taxYearOptions, []);

  const [selClient, setSelClient] = useState("");
  const [selTaxYear, setSelTaxYear] = useState(years[years.length - 2] || FORM_141_FIRST_TAX_YEAR);
  const [bundles, setBundles] = useState<PropertyDealBundle[]>([]);
  const [loading, setLoading] = useState(false);
  const [editing, setEditing] = useState<PropertyDealBundle | null>(null);
  const [saving, setSaving] = useState(false);

  // ── Agreement extraction state ───────────────────────────────────────────
  // Held here rather than in the editor so it outlives a save: the field
  // provenance and the question/answer pairs are persisted onto
  // tds_property_documents, where they stay readable long after this session.
  const [provenance, setProvenance] = useState<Record<string, FieldProvenance>>({});
  const [queries, setQueries] = useState<ResolvedQuery[]>([]);
  const [pendingDoc, setPendingDoc] = useState<StoredDocument | null>(null);
  // Reconciled challans awaiting persistence, keyed by instalment sequence.
  const [attachedChallans, setAttachedChallans] = useState<Record<number, ChallanFields>>({});

  const resetExtraction = () => {
    setProvenance({}); setQueries([]); setPendingDoc(null); setAttachedChallans({});
  };

  const handleExtracted = (applied: AppliedExtraction, doc: StoredDocument | null) => {
    setEditing(applied.bundle);
    setProvenance(applied.provenance);
    setQueries(applied.queries);
    setPendingDoc(doc);
  };

  const client = clients.find((c) => c.id === selClient) || null;

  /** Name and PAN in one label so either finds the client. */
  const clientOptions = useMemo(
    () =>
      clients.map((c) => ({
        value: c.id,
        label: `${c.name || "Unnamed"}${c.pan ? ` — ${c.pan}` : ""}`,
      })),
    [clients],
  );

  // ── Load ─────────────────────────────────────────────────────────────────
  const load = useCallback(async () => {
    if (!selClient) { setBundles([]); return; }
    setLoading(true);
    try {
      const { data: txns, error } = await propertyTable("tds_property_transactions")
        .select("*")
        .eq("client_id", selClient)
        .neq("status", "archived")
        .order("date_of_agreement", { ascending: false });
      if (error) throw error;

      const rows = (txns || []) as unknown as PropertyTransactionRow[];
      if (!rows.length) { setBundles([]); return; }

      const ids = rows.map((r) => r.id);
      const [{ data: parties }, { data: instalments }] = await Promise.all([
        propertyTable("tds_property_parties").select("*").in("transaction_id", ids),
        propertyTable("tds_property_instalments").select("*").in("transaction_id", ids),
      ]);

      const p = (parties || []) as unknown as PropertyPartyRow[];
      const i = (instalments || []) as unknown as PropertyInstalmentRow[];

      setBundles(rows.map((t) => ({
        transaction: t,
        parties: p.filter((x) => x.transaction_id === t.id),
        instalments: i.filter((x) => x.transaction_id === t.id),
      })));
    } catch (e: unknown) {
      // A missing relation means the migration has not been applied yet —
      // worth saying plainly rather than showing an empty list that looks
      // like "this client has no property transactions".
      const raw = errorMessage(e);
      const msg = /relation .* does not exist/i.test(raw)
        ? "The property TDS tables are not in this database yet. Apply migration 20260907090000_tds_property_form141.sql."
        : raw || "Could not load property transactions.";
      toast.error(msg);
      setBundles([]);
    } finally {
      setLoading(false);
    }
  }, [selClient]);

  useEffect(() => { load(); }, [load]);

  // ── PAN operativeness, from what the firm already knows ──────────────────
  //
  // An inoperative PAN carries 20% instead of 1%, and the firm usually
  // already has the answer: every TRACES PAN-verification file imported for a
  // quarterly return lands in tds_pan_verification_rows with a pan_status
  // against it. Re-typing that here would be both effort and a second chance
  // to get it wrong, so any seller whose status is still unknown is filled in
  // from the most recent verification row for the same PAN.
  //
  // Best-effort by design: no match simply leaves the status unknown, which
  // the validation layer already reports as unchecked. A failed query must
  // never block entry.
  const panLookupDone = useRef<Set<string>>(new Set());

  useEffect(() => {
    if (!editing) return;
    const wanted = editing.parties
      .filter((p) => p.party_role === "seller" && p.pan && (!p.pan_status || p.pan_status === "unknown"))
      .map((p) => p.pan as string)
      .filter((pan) => !panLookupDone.current.has(pan));
    if (!wanted.length) return;

    let cancelled = false;
    (async () => {
      for (const pan of wanted) panLookupDone.current.add(pan);
      const { data, error } = await propertyTable("tds_pan_verification_rows")
        .select("pan, pan_status, created_at")
        .in("pan", wanted)
        .order("created_at", { ascending: false });
      if (cancelled || error || !data) return;

      // First row per PAN wins — the query is newest-first.
      const latest = new Map<string, string>();
      for (const r of data as { pan: string | null; pan_status: string | null }[]) {
        if (r.pan && r.pan_status && !latest.has(r.pan)) latest.set(r.pan, r.pan_status);
      }
      if (!latest.size) return;

      let filled = 0;
      setEditing((cur) => {
        if (!cur) return cur;
        const parties = cur.parties.map((p) => {
          if (p.party_role !== "seller" || !p.pan) return p;
          if (p.pan_status && p.pan_status !== "unknown") return p;
          const status = latest.get(p.pan);
          if (!status) return p;
          // TRACES wording varies; only the two states that change the rate
          // are read strictly, and anything else is treated as operative.
          const mapped = /inoperative/i.test(status)
            ? "inoperative"
            : /invalid|not found/i.test(status)
              ? "invalid"
              : "operative";
          filled += 1;
          return { ...p, pan_status: mapped as PropertyPartyRow["pan_status"] };
        });
        return filled ? { ...cur, parties } : cur;
      });
      if (filled) {
        toast.info(
          `PAN status filled in for ${filled} seller${filled === 1 ? "" : "s"} from your PAN verification records. Check it before filing.`,
        );
      }
    })();

    return () => { cancelled = true; };
  }, [editing]);

  // ── Save ─────────────────────────────────────────────────────────────────
  //
  // Children are synced three ways — update what changed, insert what is new,
  // delete what the user removed — rather than the simpler delete-all-then-
  // reinsert. Instalments are the parent of tds_property_filings via ON DELETE
  // CASCADE, so wiping and recreating them would silently destroy the filed
  // acknowledgement, CIN and challan details attached to a payment the user
  // only meant to correct the date of.
  const save = async (statusOverride?: PropertyTxnStatus) => {
    if (!editing) return;
    setSaving(true);
    try {
      const firmId = await resolveFirmId();
      if (!firmId) throw new Error("Could not resolve your firm.");

      const t = editing.transaction;
      // Resolved ONCE, here, and written to the column — so the PAN the editor
      // showed and the PAN the filings loop computes against are the same
      // value. They used not to be, and the cost was silently discarded
      // challan details. See resolveFilingBuyerPan for the full account.
      const filingPan = resolveFilingBuyerPan(editing);
      const firstPayment = [...editing.instalments].sort((a, b) => a.seq - b.seq)[0];
      const txnPayload = {
        firm_id: firmId,
        client_id: t.client_id,
        property_type: t.property_type,
        property_address: t.property_address,
        property_pin: t.property_pin,
        date_of_agreement: t.date_of_agreement,
        date_of_registration: t.date_of_registration,
        total_sale_consideration: num(t.total_sale_consideration),
        total_stamp_duty_value: t.total_stamp_duty_value === null ? null : num(t.total_stamp_duty_value),
        stamp_duty_value_as_on: t.stamp_duty_value_as_on,
        payment_mode: t.payment_mode,
        filing_buyer_pan: filingPan || null,
        // Denormalised for listing only; the engine re-derives it per payment.
        tax_year: firstPayment ? taxYearForDate(firstPayment.date_paid_or_credited) : null,
        status: statusOverride ?? t.status,
        source: t.source,
        notes: t.notes,
      };

      let txnId = t.id;
      if (isNew(txnId)) {
        const { data, error } = await propertyTable("tds_property_transactions")
          .insert({ ...txnPayload, created_by: user?.id ?? null })
          .select("id")
          .single();
        if (error) throw error;
        txnId = (data as { id: string }).id;
      } else {
        const { error } = await propertyTable("tds_property_transactions")
          .update(txnPayload)
          .eq("id", txnId);
        if (error) throw error;
      }

      const original = bundles.find((b) => b.transaction.id === txnId);

      // Parties
      const keptPartyIds = editing.parties.filter((p) => !isNew(p.id)).map((p) => p.id);
      const removedParties = (original?.parties || []).filter((p) => !keptPartyIds.includes(p.id));
      if (removedParties.length) {
        const { error } = await propertyTable("tds_property_parties").delete().in("id", removedParties.map((p) => p.id));
        if (error) throw error;
      }
      for (const p of editing.parties) {
        const payload = {
          firm_id: firmId, transaction_id: txnId,
          party_role: p.party_role, seq: p.seq,
          pan: p.pan, name: p.name, contact: p.contact, email: p.email,
          share_pct: num(p.share_pct),
          residential_status: p.residential_status,
          entity_type: p.entity_type,
          pan_status: p.pan_status || "unknown",
          section_395_certificate_no: p.section_395_certificate_no,
          section_395_rate: p.section_395_rate === null ? null : num(p.section_395_rate),
          section_395_valid_from: p.section_395_valid_from,
          section_395_valid_to: p.section_395_valid_to,
          section_395_ceiling_amount:
            p.section_395_ceiling_amount === null ? null : num(p.section_395_ceiling_amount),
        };
        const { error } = isNew(p.id)
          ? await propertyTable("tds_property_parties").insert(payload)
          : await propertyTable("tds_property_parties").update(payload).eq("id", p.id);
        if (error) throw error;
      }

      // Instalments
      const keptInstIds = editing.instalments.filter((i) => !isNew(i.id)).map((i) => i.id);
      const removedInst = (original?.instalments || []).filter((i) => !keptInstIds.includes(i.id));
      if (removedInst.length) {
        const { error } = await propertyTable("tds_property_instalments").delete().in("id", removedInst.map((i) => i.id));
        if (error) throw error;
      }
      for (const i of editing.instalments) {
        const payload = {
          firm_id: firmId, transaction_id: txnId, seq: i.seq,
          amount_paid_by_buyer: num(i.amount_paid_by_buyer),
          date_paid_or_credited: i.date_paid_or_credited,
          date_of_deduction: i.date_of_deduction,
          date_of_deposit: i.date_of_deposit,
          date_of_filing: i.date_of_filing,
          allocations: i.allocations,
        };
        const { error } = isNew(i.id)
          ? await propertyTable("tds_property_instalments").insert(payload)
          : await propertyTable("tds_property_instalments").update(payload).eq("id", i.id);
        if (error) throw error;
      }

      // ── Filings ────────────────────────────────────────────────────────
      // A reconciled challan carries facts no computation can reproduce — the
      // acknowledgement number, the CIN, the BSR code. Written only after the
      // instalments exist, and keyed by re-reading their saved ids: a row
      // created in this save has no id until the database assigns one.
      if (Object.keys(attachedChallans).length) {
        const { data: savedInst } = await propertyTable("tds_property_instalments")
          .select("id, seq").eq("transaction_id", txnId);
        const idBySeq = new Map<number, string>(
          ((savedInst || []) as { id: string; seq: number }[]).map((r) => [r.seq, r.id]),
        );
        const computed = computeForm141ScheduleB(toForm141Deal(editing), filingPan);

        // A challan carries an acknowledgement number and a CIN that no
        // computation can reproduce and the portal will not reissue. If one
        // cannot be written, the user has to hear about it — this loop used
        // to `continue` past every failure in silence, so a save reported
        // success while dropping the only copy of the government's own
        // reference.
        const undelivered: string[] = [];

        for (const [seqStr, fields] of Object.entries(attachedChallans)) {
          const seq = Number(seqStr);
          const instalmentId = idBySeq.get(seq);
          const statement = computed.statements.find((x) => x.instalmentSeq === seq);
          if (!instalmentId || !statement) {
            undelivered.push(
              `payment ${seq}${
                computed.blockers.length
                  ? ` (${computed.blockers[0].message})`
                  : " (no statement could be computed for it)"
              }`,
            );
            continue;
          }

          const { error } = await propertyTable("tds_property_filings").upsert({
            firm_id: firmId,
            transaction_id: txnId,
            instalment_id: instalmentId,
            tax_year: statement.taxYear,
            month_of_deduction: statement.month,
            due_date: statement.dueDate,
            // What the statement SAID, frozen at the moment it was filed.
            rows_snapshot: statement.rows,
            filed_at: new Date().toISOString(),
            created_by: user?.id ?? null,
            ...challanFilingUpdate(fields),
          }, { onConflict: "instalment_id" });
          if (error) {
            console.error("property filing not recorded:", error.message);
            undelivered.push(`payment ${seq} (${error.message})`);
          }
        }

        if (undelivered.length) {
          toast.warning(
            `Challan details were not saved for ${undelivered.join("; ")}. ` +
              "The transaction itself saved — fix the blocking findings and save again to record them.",
            { duration: 12000 },
          );
        }
      }

      // The agreement and what was read from it, with every question and the
      // answer given to it. Best-effort: a transaction that saved correctly
      // must not be reported as failed because its audit trail did not write.
      if (pendingDoc) {
        const { error } = await propertyTable("tds_property_documents").insert({
          firm_id: firmId,
          transaction_id: txnId,
          doc_kind: pendingDoc.docKind,
          file_url: pendingDoc.fileUrl,
          file_name: pendingDoc.fileName,
          mime_type: pendingDoc.mimeType,
          extraction_json: { extraction: pendingDoc.extractionJson, queries, provenance },
          extraction_status: queries.some((q) => !q.resolvedAt) ? "extracted" : "confirmed",
          uploaded_by: user?.id ?? null,
        });
        if (error) console.error("property document not recorded:", error.message);
      }

      toast.success(
        statusOverride === "ready"
          ? "Transaction saved and marked ready to file."
          : "Transaction saved.",
      );
      setEditing(null);
      resetExtraction();
      await load();
    } catch (e: unknown) {
      toast.error(errorMessage(e) || "Could not save the transaction.");
    } finally {
      setSaving(false);
    }
  };

  const startNew = async () => {
    const firmId = await resolveFirmId();
    if (!firmId) { toast.error("Could not resolve your firm."); return; }
    resetExtraction();
    const txn = emptyTransaction(selClient, firmId);
    setEditing({
      transaction: txn,
      // The client is a buyer by definition — pre-seeded with their own PAN so
      // the single-buyer case (much the commonest) needs no party entry at all.
      parties: [{
        id: "new-buyer-1", firm_id: firmId, transaction_id: "", party_role: "buyer", seq: 1,
        pan: client?.pan || null, name: client?.name || "", contact: null, email: null,
        // Residency is never read for a buyer — only a seller's picks the
        // statute — so this value is inert and left as the plain case.
        share_pct: 100, residential_status: "resident", pan_status: "unknown", entity_type: null,
        section_395_certificate_no: null, section_395_rate: null,
        section_395_valid_from: null, section_395_valid_to: null,
        section_395_ceiling_amount: null,
      }],
      instalments: [],
    });
  };

  // ── List figures ─────────────────────────────────────────────────────────
  // Computed ABOVE the editor's early return, because hooks must run in the
  // same order on every render and the editor branch returns before the list
  // is ever reached.
  const visible = useMemo(
    () => bundles.filter((b) => !selTaxYear || !b.transaction.tax_year || b.transaction.tax_year === selTaxYear),
    [bundles, selTaxYear],
  );

  /**
   * The list's figures, computed once per change rather than once per render.
   *
   * Every row runs the full engine — mapping, threshold, apportionment,
   * interest and fee across every instalment and seller. Unmemoised that ran
   * again on each keystroke in the header controls and on every unrelated
   * state change; at forty property deals it was visible.
   */
  const listRows = useMemo(
    () =>
      visible.map((b) => {
        const deal = toForm141Deal(b);
        const computed = computeForm141ScheduleB(deal, resolveFilingBuyerPan(b));
        const nextDue = computed.statements.find((st) => {
          const inst = b.instalments.find((i) => i.seq === st.instalmentSeq);
          return !inst?.date_of_deposit;
        });
        return { bundle: b, deal, computed, nextDue };
      }),
    [visible],
  );

  // ── Editor ───────────────────────────────────────────────────────────────
  if (editing) {
    return (
      <div>
        <div className="mb-4 flex items-center gap-3">
          <Button variant="ghost" size="sm" onClick={() => { setEditing(null); resetExtraction(); }} disabled={saving}>
            <ArrowLeft size={14} className="mr-1.5" /> Back
          </Button>
          <div>
            <h2 className="text-lg font-bold">
              {isNew(editing.transaction.id) ? "New property transaction" : "Property transaction"}
            </h2>
            <p className="text-xs text-muted-foreground">
              {client?.name} · Form 141 Schedule B · TDS on transfer of immovable property
            </p>
          </div>
        </div>
        <TdsPropertyEditor
          bundle={editing}
          onChange={setEditing}
          onSave={save}
          onCancel={() => { setEditing(null); resetExtraction(); }}
          saving={saving}
          selectedClientPan={client?.pan || null}
          selectedTaxYear={selTaxYear}
          provenance={provenance}
          queries={queries}
          onExtracted={handleExtracted}
          onProvenanceChange={setProvenance}
          onQueriesChange={setQueries}
          attachedChallans={attachedChallans}
          onAttachChallan={(seq, fields) => setAttachedChallans((m) => ({ ...m, [seq]: fields }))}
        />
      </div>
    );
  }


  return (
    <div>
      <div className="mb-4">
        <h2 className="text-xl font-bold flex items-center gap-2">
          <Home size={18} /> TDS on Property
        </h2>
        <p className="text-sm text-muted-foreground">
          Form 141 Schedule B — TDS on transfer of immovable property under section 393(1), filed under the
          buyer&apos;s PAN. Separate from the quarterly returns: one statement per payment, due 30 days from
          the end of the month of deduction.
        </p>
      </div>

      <Card className="mb-4">
        <CardContent className="pt-5">
          <div className="flex flex-wrap gap-4 items-end">
            <div className="space-y-1.5 min-w-[280px]">
              <Label>Client</Label>
              {/* Type-to-search rather than a bare dropdown: a firm with several
                  hundred clients cannot scroll to one, and the PAN is in the
                  label so a client can be found by either. */}
              <SearchableSelect
                className="w-full"
                options={clientOptions}
                value={selClient}
                onValueChange={setSelClient}
                placeholder="Select a client"
                searchPlaceholder="Search by name or PAN…"
                emptyText="No client matches that."
              />
            </div>
            <div className="space-y-1.5 w-[140px]">
              <Label>Tax Year</Label>
              <Select value={selTaxYear} onValueChange={setSelTaxYear}>
                <SelectTrigger><SelectValue /></SelectTrigger>
                <SelectContent>
                  {years.map((y) => <SelectItem key={y} value={y}>{y}</SelectItem>)}
                </SelectContent>
              </Select>
            </div>
            <div className="flex-1" />
            <Button onClick={startNew} disabled={!selClient}>
              <Plus size={14} className="mr-1.5" /> New transaction
            </Button>
          </div>
        </CardContent>
      </Card>

      {!selClient && (
        <Card><CardContent className="py-10 text-center text-sm text-muted-foreground">
          Select a client to see their property transactions.
        </CardContent></Card>
      )}

      {selClient && loading && (
        <div className="space-y-2">
          {[0, 1, 2].map((i) => <Skeleton key={i} className="h-16 w-full" />)}
        </div>
      )}

      {selClient && !loading && visible.length === 0 && (
        <Card><CardContent className="py-10 text-center">
          <p className="text-sm text-muted-foreground mb-3">
            No property transactions recorded for {client?.name} in {selTaxYear}.
          </p>
          <Button variant="outline" onClick={startNew}>
            <Plus size={14} className="mr-1.5" /> Record one
          </Button>
        </CardContent></Card>
      )}

      {selClient && !loading && visible.length > 0 && (
        <div className="space-y-2">
          {listRows.map(({ bundle: b, deal, computed, nextDue }) => {
            return (
              <Card
                key={b.transaction.id}
                className="cursor-pointer hover:border-primary/40 transition-colors"
                onClick={() => { resetExtraction(); setEditing(b); }}
              >
                <CardContent className="py-3.5">
                  <div className="flex items-start justify-between gap-4">
                    <div className="min-w-0">
                      <div className="flex items-center gap-2 mb-0.5">
                        <span className="font-medium text-sm truncate">
                          {b.transaction.property_type}
                          {b.transaction.property_address ? ` · ${b.transaction.property_address}` : ""}
                        </span>
                        <Badge className={cn("text-[10px] shrink-0", STATUS_BADGE[b.transaction.status])}>
                          {STATUS_LABEL[b.transaction.status]}
                        </Badge>
                      </div>
                      <p className="text-xs text-muted-foreground">
                        Agreement {b.transaction.date_of_agreement} ·{" "}
                        {formatInr(b.transaction.total_sale_consideration)} ·{" "}
                        {deal.sellers.length} seller{deal.sellers.length === 1 ? "" : "s"} ·{" "}
                        {b.instalments.length} payment{b.instalments.length === 1 ? "" : "s"}
                      </p>
                      {nextDue && (
                        <p className="text-xs text-amber-700 dark:text-amber-400 mt-1 flex items-center gap-1.5">
                          <CalendarClock size={12} />
                          {formatInr(nextDue.totalPayable)} due {nextDue.dueDate} ({nextDue.month})
                        </p>
                      )}
                    </div>
                    <div className="text-right shrink-0">
                      <p className="text-sm font-semibold tabular-nums">{formatInr(computed.grandTotalTds)}</p>
                      <p className="text-[11px] text-muted-foreground">tax deducted</p>
                      {computed.blockers.length > 0 && (
                        <Badge className="mt-1 text-[10px] bg-red-100 text-red-700 dark:bg-red-900/30 dark:text-red-300">
                          {computed.blockers.length} blocking
                        </Badge>
                      )}
                    </div>
                  </div>
                </CardContent>
              </Card>
            );
          })}
        </div>
      )}
    </div>
  );
}
