const BORDER_GREY = { style: BorderStyle.SINGLE, size: 4, color: "BFBFBF" };
const BORDERS_GREY = { top: BORDER_GREY, bottom: BORDER_GREY, left: BORDER_GREY, right: BORDER_GREY };
const NO_BORDER = { style: BorderStyle.NONE, size: 0, color: "FFFFFF" };
const BORDERS_NONE = { top: NO_BORDER, bottom: NO_BORDER, left: NO_BORDER, right: NO_BORDER };

const GREEN = "008000";
