-- ─── Authorized Telegram Users ──────────────────────────────────
-- Admin adds telegram_user_id + firm_id to grant bot access
-- Users can also self-link via /start link_<token>

CREATE TABLE IF NOT EXISTS telegram_authorized_users (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  telegram_user_id    BIGINT NOT NULL UNIQUE,        -- Telegram numeric user ID
  telegram_chat_id    BIGINT NOT NULL,               -- Chat ID for sending messages
  telegram_username   TEXT,                          -- @handle (optional)
  telegram_first_name TEXT,                          -- Display name
  firm_id             UUID NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  user_id             UUID REFERENCES users(id) ON DELETE SET NULL,
  is_active           BOOLEAN DEFAULT true NOT NULL,
  linked_at           TIMESTAMPTZ DEFAULT NOW(),
  last_used_at        TIMESTAMPTZ,
  created_at          TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tg_auth_telegram_uid ON telegram_authorized_users(telegram_user_id);
CREATE INDEX IF NOT EXISTS idx_tg_auth_firm         ON telegram_authorized_users(firm_id);

-- ─── Link Tokens ─────────────────────────────────────────────────
-- Generated by admin in CAFlow UI; user clicks deep-link to link account
-- Token expires after 1 hour and can only be used once

CREATE TABLE IF NOT EXISTS telegram_link_tokens (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  token      TEXT NOT NULL UNIQUE,
  firm_id    UUID NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  user_id    UUID REFERENCES users(id) ON DELETE CASCADE,
  used       BOOLEAN DEFAULT false NOT NULL,
  expires_at TIMESTAMPTZ DEFAULT (NOW() + INTERVAL '1 hour'),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tg_tokens_token ON telegram_link_tokens(token);

-- ─── RLS ──────────────────────────────────────────────────────────
-- Service role bypasses RLS; these tables are accessed only by edge functions
ALTER TABLE telegram_authorized_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE telegram_link_tokens ENABLE ROW LEVEL SECURITY;

-- Superadmin can manage all rows
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE tablename = 'telegram_authorized_users' AND policyname = 'superadmin_all'
  ) THEN
    CREATE POLICY superadmin_all ON telegram_authorized_users
      FOR ALL TO authenticated
      USING (
        EXISTS (SELECT 1 FROM users WHERE id = auth.uid() AND role = 'superadmin')
      );
  END IF;
END $$;

