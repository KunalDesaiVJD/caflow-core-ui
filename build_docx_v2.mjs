function P(text, opts = {}) {
  return new Paragraph({
    alignment: opts.align ?? AlignmentType.LEFT,
    spacing: opts.spacing ?? { after: 120 },
    children: [new TextRun({ text, bold: opts.bold, size: opts.size ?? 22,
      color: opts.color, font: "Arial" })],
  });
}
function H1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 240, after: 240 },
    children: [new TextRun({ text, bold: true, size: 32, color: BLUE, font: "Arial" })],
  });
}
function H2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 200, after: 160 },
    children: [new TextRun({ text, bold: true, size: 28, color: BLUE, font: "Arial" })],
  });
}
function Cell(text, opts = {}) {
  return new TableCell({
    borders: opts.borderless ? BORDERS_NONE : BORDERS_GREY,
    width: { size: opts.width ?? 4680, type: WidthType.DXA },
    shading: opts.shade ? { fill: opts.shade, type: ShadingType.CLEAR, color: "auto" } : undefined,
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [new Paragraph({
      alignment: opts.align ?? AlignmentType.LEFT,
      children: [new TextRun({ text, bold: opts.bold, color: opts.color, size: 20, font: "Arial" })],
    })],
  });
}
function row(cells) { return new TableRow({ children: cells }); }
function pageBreak() { return new Paragraph({ children: [new PageBreak()] }); }

